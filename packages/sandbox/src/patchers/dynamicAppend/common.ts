import { qiankunHeadTagName } from '../../consts';
import type { SandboxConfig } from './types';

const SCRIPT_TAG_NAME = 'SCRIPT';
const LINK_TAG_NAME = 'LINK';
const STYLE_TAG_NAME = 'STYLE';

export const styleElementTargetSymbol = Symbol('target');
export const styleElementRefNodeNo = Symbol('refNodeNo');
const overwrittenSymbol = Symbol('qiankun-overwritten');

type DynamicDomMutationTarget = 'head' | 'body';

declare global {
  interface HTMLLinkElement {
    [styleElementTargetSymbol]: DynamicDomMutationTarget;
    [styleElementRefNodeNo]?: Exclude<number, -1>;
  }

  interface HTMLStyleElement {
    [styleElementTargetSymbol]: DynamicDomMutationTarget;
    [styleElementRefNodeNo]?: Exclude<number, -1>;
  }

  interface Function {
    [overwrittenSymbol]: boolean;
  }
}

export const getContainerHeadElement = (container: Element): HTMLHeadElement | null => {
  return container.querySelector(qiankunHeadTagName);
};

export const getContainerBodyElement = (container: Element): HTMLBodyElement => {
  return container as HTMLBodyElement;
};

export function isHijackingTag(tagName?: string) {
  return (
    tagName?.toUpperCase() === LINK_TAG_NAME ||
    tagName?.toUpperCase() === STYLE_TAG_NAME ||
    tagName?.toUpperCase() === SCRIPT_TAG_NAME
  );
}

/**
 * Check if a style element is a styled-component liked.
 * A styled-components liked element is which not have textContext but keep the rules in its styleSheet.cssRules.
 * Such as the style element generated by styled-components and emotion.
 * @param element
 */
export function isStyledComponentsLike(element: HTMLStyleElement): boolean {
  return Boolean(!element.textContent && (element.sheet?.cssRules.length || getStyledElementCSSRules(element)?.length));
}

const defineNonEnumerableProperty = (target: unknown, key: string | symbol, value: unknown) => {
  Object.defineProperty(target, key, {
    configurable: true,
    enumerable: false,
    writable: true,
    value,
  });
};

const styledComponentCSSRulesMap = new WeakMap<HTMLStyleElement, CSSRuleList>();

export function recordStyledComponentsCSSRules(styleElements: HTMLStyleElement[]): void {
  styleElements.forEach((styleElement) => {
    /*
     With a styled-components generated style element, we need to record its cssRules for restore next re-mounting time.
     We're doing this because the sheet of style element is going to be cleaned automatically by browser after the style element dom removed from document.
     see https://www.w3.org/TR/cssom-1/#associated-css-style-sheet
     */
    if (styleElement instanceof HTMLStyleElement && isStyledComponentsLike(styleElement)) {
      if (styleElement.sheet) {
        // record the original css rules of the style element for restore
        styledComponentCSSRulesMap.set(styleElement, styleElement.sheet.cssRules);
      }
    }
  });
}

export function getStyledElementCSSRules(styledElement: HTMLStyleElement): CSSRuleList | undefined {
  return styledComponentCSSRulesMap.get(styledElement);
}

/**
 * Nodes a remount does not stream into the fresh container again: every hijackable element that
 * went through the dynamic pipeline (stylesheets are replayed from the ledger, scripts never).
 */
function isDynamicNode(node: Node, getSandboxConfig: (element: HTMLElement) => SandboxConfig | undefined): boolean {
  return isHijackingTag((node as Element).tagName) && !!getSandboxConfig(node as HTMLElement);
}

/**
 * The position of a stylesheet within the static content of its parent, i.e. the number of
 * static nodes preceding it. Unlike a plain child index it does not depend on the other dynamic
 * nodes, which may be moved, removed or replayed in a different sequence before a remount.
 */
function getStaticNodeNo(element: Node, getSandboxConfig: (element: HTMLElement) => SandboxConfig | undefined): number {
  let staticNodeNo = 0;
  for (let sibling = element.previousSibling; sibling; sibling = sibling.previousSibling) {
    if (!isDynamicNode(sibling, getSandboxConfig)) staticNodeNo += 1;
  }
  return staticNodeNo;
}

/**
 * Find the static child node a replayed stylesheet must be inserted before, `null` meaning the end.
 */
export function getStaticChildNode(
  parent: Node,
  staticNodeNo: number,
  getSandboxConfig: (element: HTMLElement) => SandboxConfig | undefined,
): ChildNode | null {
  let remaining = staticNodeNo;
  for (let child = parent.firstChild; child; child = child.nextSibling) {
    if (!isDynamicNode(child, getSandboxConfig)) {
      if (remaining === 0) return child;
      remaining -= 1;
    }
  }
  return null;
}

/**
 * Record a stylesheet in the ledger at its document position, thus remounts replay the
 * stylesheets in the order they had at last, wherever they have been moved to in between.
 */
function recordDynamicStyleSheetElement(
  dynamicStyleSheetElements: SandboxConfig['dynamicStyleSheetElements'],
  stylesheetElement: HTMLLinkElement | HTMLStyleElement,
): void {
  // moving an already recorded element updates its entry instead of recording it twice,
  // otherwise a single removal would leave a stale entry that remounts replay
  const recordedIndex = dynamicStyleSheetElements.indexOf(stylesheetElement);
  if (recordedIndex !== -1) {
    dynamicStyleSheetElements.splice(recordedIndex, 1);
  }

  // appending is the common case, so look for the position from the end of the ledger
  let index = dynamicStyleSheetElements.length;
  while (index > 0) {
    const position = stylesheetElement.compareDocumentPosition(dynamicStyleSheetElements[index - 1]);
    // the order of elements living in different trees (e.g. a cleared container) is unknown
    if (position & Node.DOCUMENT_POSITION_DISCONNECTED || !(position & Node.DOCUMENT_POSITION_FOLLOWING)) break;
    index -= 1;
  }
  dynamicStyleSheetElements.splice(index, 0, stylesheetElement);
}

export function getOverwrittenAppendChildOrInsertBefore(
  nativeFn: typeof HTMLElement.prototype.appendChild | typeof HTMLElement.prototype.insertBefore,
  getSandboxConfig: (element: HTMLElement) => SandboxConfig | undefined,
  target: DynamicDomMutationTarget = 'body',
  setSandboxConfig?: (element: HTMLElement, config: SandboxConfig) => void,
) {
  /**
   * @param anchorNode the node the insertion is positioned against, which is the reference node
   * unless the caller positions it otherwise (e.g. `insertAdjacentElement('afterend')` right after
   * the last child of the mount point)
   */
  function appendChildInSandbox<T extends Node>(
    this: HTMLHeadElement | HTMLBodyElement,
    newChild: T,
    refChild: Node | null = null,
    anchorNode: Node | null = refChild,
  ): T {
    const appendChild = nativeFn;

    const element = newChild as unknown as HTMLElement;

    // jQuery-style insertions wrap nodes in a DocumentFragment, which would smuggle style/script
    // elements past the per-tag hijacking below — decompose such a fragment and route every child
    // through the same pipeline (a fragment empties on insertion natively, so per-child appends
    // keep the same end state and order). Nodes marked for native passthrough (the loader's
    // pipeline batches its processed nodes into fragments for insertion performance) must pass
    // through untouched, never through the pipeline again.
    if (element.nodeType === Node.DOCUMENT_FRAGMENT_NODE) {
      const fragment = newChild as unknown as DocumentFragment;
      const shouldDecompose =
        !!getSandboxConfig(this) &&
        Array.from(fragment.children).some((child) => isHijackingTag(child.tagName) && !isNativePassthroughNode(child));
      if (shouldDecompose) {
        Array.from(fragment.childNodes).forEach((child) => {
          appendChildInSandbox.call(this, child, refChild, anchorNode);
        });
        return newChild;
      }
    }

    // insertion-point ownership: a hijackable element landing on a patched mount point belongs to
    // the app owning that mount point, no matter who created it — except nodes a qiankun pipeline
    // marked for native passthrough, which must pass through untouched.
    // See docs/rfcs/insertion-point-ownership.md.
    const sandboxConfig = isNativePassthroughNode(element) ? undefined : getSandboxConfig(this);

    if (!isHijackingTag(element.tagName) || !sandboxConfig) {
      return appendChild.call(this, element, refChild) as T;
    }

    // Register the element under its insertion owner so the patched removeChild and the CSSOM
    // patch can recognize it later — otherwise its ledger entry would replay on every remount.
    // Re-insertion re-attributes: an element moved across mount points follows its new owner.
    const previousConfig = getSandboxConfig(element);
    if (previousConfig && previousConfig !== sandboxConfig) {
      warn(
        `Element ${element.tagName.toLowerCase()} previously owned by ${previousConfig.appName} is re-attributed to ${sandboxConfig.appName} as it is inserted into the latter's container`,
      );
    }
    setSandboxConfig?.(element, sandboxConfig);

    if (element.tagName) {
      switch (element.tagName) {
        case LINK_TAG_NAME:
        case STYLE_TAG_NAME: {
          const stylesheetElement = element as HTMLLinkElement | HTMLStyleElement;

          /*
           * Only rel=stylesheet links belong to the dynamic-stylesheet ledger that remounts
           * replay. Hint links (preload/modulepreload/preconnect/icon/…) still run through the
           * transformer — their URLs must resolve against the app entry and preload requests must
           * stay matchable by the pipeline fetch — but recording them would re-issue the hints on
           * every remount, and a hint's own removal could never settle the entry.
           */
          if (
            element.tagName === LINK_TAG_NAME &&
            !(stylesheetElement as HTMLLinkElement).relList.contains('stylesheet')
          ) {
            const { compartment, nodeTransformer, fetch, styleIsolation } = sandboxConfig;
            const transpiledHintElement = nodeTransformer(stylesheetElement, { compartment, fetch, styleIsolation });
            return appendChild.call(this, transpiledHintElement, refChild) as T;
          }

          Object.defineProperty(stylesheetElement, styleElementTargetSymbol, {
            value: target,
            writable: true,
            configurable: true,
          });

          const referenceNode = this.contains(refChild) ? refChild : null;

          const { compartment, nodeTransformer, fetch, styleIsolation } = sandboxConfig;
          const transpiledStyleSheetElement = nodeTransformer(stylesheetElement, {
            compartment,
            fetch,
            styleIsolation,
          });

          if (transpiledStyleSheetElement !== stylesheetElement && setSandboxConfig) {
            setSandboxConfig(transpiledStyleSheetElement as HTMLElement, sandboxConfig);
          }

          const stylesheetTargetDetached = !document.contains(this);
          if (stylesheetTargetDetached) {
            warn(
              `Trying to append stylesheet element ${
                ('href' in transpiledStyleSheetElement && transpiledStyleSheetElement.href) ||
                transpiledStyleSheetElement.dataset.href
              } to a detached container which may cause unexpected behaviors!`,
            );
          }
          // FIXME we have to set the target container to global document to trigger style rendering while the real container was detached
          // An insertion positioned against a node living in the detached container can only land there,
          // the global document would reject a reference node as it is not its child.
          const targetContainerDOM =
            stylesheetTargetDetached && anchorNode?.parentNode !== this ? document[target] : this;
          const result = appendChild.call(targetContainerDOM, transpiledStyleSheetElement, referenceNode);

          // record the position among the static nodes thus we can keep order while remounting
          if (referenceNode && transpiledStyleSheetElement.parentNode === this) {
            defineNonEnumerableProperty(
              transpiledStyleSheetElement,
              styleElementRefNodeNo,
              getStaticNodeNo(transpiledStyleSheetElement, getSandboxConfig),
            );
          } else {
            // a moved element must not keep the position it was recorded at before
            Reflect.deleteProperty(transpiledStyleSheetElement, styleElementRefNodeNo);
          }
          // the previous owner must not replay an element that moved into another sandbox
          if (previousConfig && previousConfig !== sandboxConfig) {
            const previousIndex = previousConfig.dynamicStyleSheetElements.indexOf(transpiledStyleSheetElement);
            if (previousIndex !== -1) {
              previousConfig.dynamicStyleSheetElements.splice(previousIndex, 1);
            }
          }
          // record dynamic style elements after insert succeed
          recordDynamicStyleSheetElement(sandboxConfig.dynamicStyleSheetElements, transpiledStyleSheetElement);

          return result as T;
        }

        case SCRIPT_TAG_NAME: {
          const scriptElement = element as HTMLScriptElement;
          const { compartment, dynamicExternalSyncScriptDeferredList, nodeTransformer, fetch } = sandboxConfig;

          const externalSyncMode = scriptElement.hasAttribute('src') && !scriptElement.hasAttribute('async');

          let transformerOpts: AssetsTranspilerOpts = {
            compartment,
            fetch,
          };

          let queueSyncScript: () => void;
          if (externalSyncMode) {
            const { deferred, prevDeferred, queue } = prepareDeferredQueue(dynamicExternalSyncScriptDeferredList);
            transformerOpts = {
              ...transformerOpts,
              scriptTranspiledDeferred: deferred,
              prevScriptTranspiledDeferred: prevDeferred,
            } as ScriptTranspilerOpts;
            queueSyncScript = queue;
          }

          const transpiledScriptElement = nodeTransformer(scriptElement, transformerOpts);

          /*
            The target container of script element might be removed from current document.
            For example, the main application clears the DOM first during route switching, and then trigger unmount,
            at this time, the micro app may still be processing the logic of the route switching, and try to add nodes to the detached container,
            in this scenario, we have to append the script to global document head to trigger script evaluation
           */
          const scriptTargetDetached = !document.contains(this);
          if (scriptTargetDetached) {
            warn(
              `Trying to append script element ${
                transpiledScriptElement.src || transpiledScriptElement.dataset.src
              } to a detached container which may cause unexpected behaviors!`,
            );
          }
          /*
           FIXME we have to set the target container to global document to trigger script evaluation while the real container was detached,
           as dynamic append script element to detached element will not trigger script evaluation automatically.
           Unlike a stylesheet, a script stays in the detached container only when its reference node lives there,
           an insertion merely anchored there (e.g. `afterend` of the last child) still goes to the global document
           */
          const targetContainerDOM = scriptTargetDetached && refChild?.parentNode !== this ? document[target] : this;
          const result = appendChild.call(targetContainerDOM, transpiledScriptElement, refChild) as T;

          // the script have no src attribute after transpile, indicating that the script needs to wait for the src to be filled
          if (externalSyncMode && !transpiledScriptElement.hasAttribute('src')) {
            queueSyncScript!();
          }

          return result;
        }

        default:
          break;
      }
    }

    return appendChild.call(this, element, refChild) as T;
  }

  appendChildInSandbox[overwrittenSymbol] = true;

  return appendChildInSandbox;
}

export function getNewRemoveChild(
  nativeFn: typeof HTMLElement.prototype.removeChild,
  containerConfigGetter: (element: HTMLElement) => SandboxConfig | undefined,
) {
  function removeChildInSandbox<T extends Node>(this: HTMLHeadElement | HTMLBodyElement, child: T): T {
    const removeChild = nativeFn;

    const childElement = child as unknown as HTMLElement;
    const { tagName } = childElement;
    const containerConfig = containerConfigGetter(childElement);

    if (!isHijackingTag(tagName) || !containerConfig) {
      return removeChild.call(this, childElement) as T;
    }

    try {
      const { dynamicStyleSheetElements } = containerConfig;

      switch (tagName) {
        case STYLE_TAG_NAME:
        case LINK_TAG_NAME: {
          // try to remove the dynamic style sheet
          const dynamicElementIndex = dynamicStyleSheetElements.indexOf(
            childElement as HTMLLinkElement | HTMLStyleElement,
          );
          if (dynamicElementIndex !== -1) {
            dynamicStyleSheetElements.splice(dynamicElementIndex, 1);
          }

          break;
        }

        default: {
          break;
        }
      }

      // container might have been removed while app unmounting if the removeChild action was async
      if (this.contains(childElement)) {
        return removeChild.call(this, childElement) as T;
      }
    } catch (e) {
      console.warn(e);
    }

    return removeChild.call(this, childElement) as T;
  }

  removeChildInSandbox[overwrittenSymbol] = true;
  return removeChildInSandbox;
}

export function rebuildCSSRules(
  styleSheetElements: Array<HTMLStyleElement | HTMLLinkElement>,
  reAppendElement: (stylesheetElement: HTMLStyleElement | HTMLLinkElement) => Promise<boolean>,
): Array<Promise<void>> {
  return styleSheetElements.map(async (styleSheetElement) => {
    // re-append the dynamic stylesheet to sub-app container
    const appendSuccess = await reAppendElement(styleSheetElement);
    if (appendSuccess) {
      /*
      get the stored css rules from styled-components generated element, and the re-insert rules for them.
      note that we must do this after style element had been added to document, which stylesheet would be associated to the document automatically.
      check the spec https://www.w3.org/TR/cssom-1/#associated-css-style-sheet
       */
      if (styleSheetElement instanceof HTMLStyleElement && isStyledComponentsLike(styleSheetElement)) {
        const cssRules = getStyledElementCSSRules(styleSheetElement);
        if (cssRules) {
          // eslint-disable-next-line no-plusplus
          for (let i = 0; i < cssRules.length; i++) {
            const cssRule = cssRules[i];
            const cssStyleSheetElement = styleSheetElement.sheet as CSSStyleSheet;
            cssStyleSheetElement.insertRule(cssRule.cssText, cssStyleSheetElement.cssRules.length);
          }
        }
      }
    }
  });
}
